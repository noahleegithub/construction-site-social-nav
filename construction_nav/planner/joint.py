"""Joint predictor + planner for social navigation (design Section 4).

The planner couples the learned *joint* predictor to a safety-filtered
model-predictive controller:

1. **Predict.** The agents' futures are forecast with the multimodal predictor
   (constant velocity, reduced Trajectron++, or the diffusion model). In the
   ``safety_diffusion`` mode the diffusion sampler is additionally *conditioned*
   on the robot's intended route plan and the robot's rows are projected onto the
   hard-constraint safe set **inside reverse diffusion**, so the forecast already
   reflects a collision-free robot trajectory.
2. **Propose.** A small set of local manoeuvres is generated by integrating the
   unicycle along the robot's graph route at several speed scales and heading
   offsets.
3. **Score.** Each manoeuvre is scored with the Eq. (3) ingredients against every
   predicted mode, using the *per-type* ``D_S`` / ``D_C``: a progress term (a
   travel-time proxy), the soft safety integral ``lambda_1 * sum max(0, -h_C)``,
   the freeze penalty ``lambda_2 * T_freeze``, and a hard-constraint feasibility
   test on ``h_S >= 0``.
4. **Filter.** The chosen command is passed through a reactive clearance guard
   that scales the speed to zero as the robot approaches ``D_S`` -- this enforces
   the hard constraint against the *real* state even when the forecast is wrong.

``oracle=True`` replaces the predictor with perfect future knowledge, giving the
perfect-knowledge planner baseline on the same controller.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from construction_nav import config as C
from construction_nav.dynamics import unicycle_step, wrap_angle
from construction_nav.env import ConstructionEnv
from construction_nav.planner.base import (
    Planner,
    oracle_futures,
    route_direction,
    unicycle_command,
)


@dataclass
class Manoeuvre:
    """A candidate local robot trajectory."""

    path: np.ndarray                 # (Hp, 2) site metres
    command: tuple[float, float]     # first (v, omega)
    speed: float                     # nominal speed of the manoeuvre
    freeze: bool                     # manoeuvre is (nearly) stationary


class JointPlanner(Planner):
    """Multimodal-prediction model-predictive planner with a safety filter."""

    def __init__(
        self,
        predictor=None,
        plan_horizon: int = 8,
        speed_scales: tuple[float, ...] = (1.0, 0.6, 0.3, 0.0),
        heading_offsets_deg: tuple[float, ...] = (-25.0, 0.0, 25.0),
        lambda_intrusion: float = 1.0,
        lambda_freeze: float = 0.5,
        hard_filter: bool = True,
        guard_factor: float = 0.5,
        safety_diffusion: bool = False,
        safety_margin: float = 0.0,
        oracle: bool = False,
        label: str | None = None,
    ) -> None:
        self.predictor = predictor
        self.plan_horizon = plan_horizon
        self.speed_scales = tuple(speed_scales)
        self.heading_offsets = np.deg2rad(np.asarray(heading_offsets_deg, dtype=float))
        self.lambda_intrusion = lambda_intrusion
        self.lambda_freeze = lambda_freeze
        self.hard_filter = hard_filter
        self.guard_factor = guard_factor
        self.safety_diffusion = safety_diffusion
        self.safety_margin = safety_margin
        self.oracle = oracle
        self._label = label
        self.last_cost: float | None = None
        self.last_infeasible: bool = False

    # -- naming ------------------------------------------------------------

    @property
    def name(self) -> str:
        if self._label:
            return self._label
        if self.oracle:
            return "MPC + perfect trajectory forecasting"
        pred = getattr(self.predictor, "name", type(self.predictor).__name__)
        return f"joint planner ({pred})"

    # -- prediction --------------------------------------------------------

    @property
    def horizon(self) -> int:
        if self.oracle:
            return max(self.plan_horizon, C.HORIZON_STEPS)
        return int(getattr(self.predictor, "horizon", C.HORIZON_STEPS))

    def _nominal_plan(self, env: ConstructionEnv) -> np.ndarray:
        """Route-following unicycle rollout from the current pose, ``(H, 2)``."""
        desired = route_direction(env) * env.layout.robot_speed
        path, _ = self._integrate(env, desired, self.horizon)
        return path

    def _agent_modes(self, env: ConstructionEnv) -> tuple[np.ndarray, np.ndarray]:
        """Return ``(samples (M, K, H, 2), weights (M, K))`` in site metres."""
        m = len(env.scene.agents)
        if self.oracle:
            futures = oracle_futures(env, self.horizon)
            return futures[:, None], np.ones((m, 1))

        if self.safety_diffusion and hasattr(self.predictor, "sample_joint"):
            ds = np.array([a.D_S for a in env.scene.agents], dtype=float)
            joint = self.predictor.sample_joint(
                env.observe(),
                robot_plan=self._nominal_plan(env),
                ds_agents=ds,
                safety_margin=self.safety_margin,
            )                                             # (K, N, H, 2)
            k = joint.shape[0]
            agent_samples = np.transpose(joint[:, :m], (1, 0, 2, 3))  # (M, K, H, 2)
            return agent_samples, np.full((m, k), 1.0 / k)

        out = self.predictor.predict(env.observe())
        if out.samples is not None:
            return out.samples, out.weights
        return out.mean[:, None], np.ones((m, 1))

    # -- manoeuvre generation ---------------------------------------------

    def _integrate(
        self, env: ConstructionEnv, desired_velocity: np.ndarray, steps: int
    ) -> tuple[np.ndarray, np.ndarray]:
        pos = env.robot.pos.copy()
        theta = env.robot.theta
        path = np.zeros((steps, 2))
        commands = np.zeros((steps, 2))
        for i in range(steps):
            v, omega = unicycle_command(pos, theta, desired_velocity, env.layout.robot_speed)
            pos, theta = unicycle_step(pos, theta, v, omega, env.dt)
            path[i] = pos
            commands[i] = (v, omega)
        return path, commands

    def _manoeuvres(self, env: ConstructionEnv) -> list[Manoeuvre]:
        base = route_direction(env)
        steps = min(self.plan_horizon, self.horizon)
        out: list[Manoeuvre] = []
        for scale in self.speed_scales:
            for offset in self.heading_offsets:
                rot = np.array(
                    [[np.cos(offset), -np.sin(offset)], [np.sin(offset), np.cos(offset)]]
                )
                desired = rot @ base * (env.layout.robot_speed * scale)
                path, commands = self._integrate(env, desired, steps)
                out.append(
                    Manoeuvre(
                        path=path,
                        command=(float(commands[0, 0]), float(commands[0, 1])),
                        speed=float(env.layout.robot_speed * scale),
                        freeze=scale <= 1e-6,
                    )
                )
        return out

    # -- scoring -----------------------------------------------------------

    def _score(
        self,
        env: ConstructionEnv,
        candidate: Manoeuvre,
        samples: np.ndarray,
        weights: np.ndarray,
    ) -> tuple[float, float]:
        """Return ``(cost, expected hard violation)`` for one manoeuvre."""
        steps = candidate.path.shape[0]
        robot_path = candidate.path                        # (Hp, 2)
        modes = np.transpose(samples[:, :, :steps, :], (1, 2, 0, 3))  # (K, Hp, M, 2)

        delta = robot_path[None, :, None, :] - modes        # (K, Hp, M, 2)
        dist = np.linalg.norm(delta, axis=-1)               # (K, Hp, M)

        d_s = np.array([a.D_S for a in env.scene.agents], float)[None, None, :]
        d_c = np.array([a.D_C for a in env.scene.agents], float)[None, None, :]
        h_s = dist**2 - d_s**2
        h_c = dist**2 - d_c**2

        w = np.transpose(weights, (1, 0))[:, None, :]       # (K, 1, M)
        soft = float(np.sum(np.maximum(0.0, -h_c) * w)) * env.dt
        hard = float(np.sum(np.maximum(0.0, -h_s) * w))

        goal = env.robot.goal
        start_d = float(np.linalg.norm(goal - robot_path[0]))
        end_d = float(np.linalg.norm(goal - robot_path[-1]))
        progress = start_d - end_d                          # > 0 towards the goal

        freeze = float(candidate.freeze) * steps * env.dt
        cost = (
            -progress
            + self.lambda_intrusion * soft
            + self.lambda_freeze * freeze
        )
        return cost, hard

    # -- reactive hard-constraint guard -----------------------------------

    def _guard(self, env: ConstructionEnv, v: float, omega: float) -> tuple[float, float]:
        """Scale the speed down to zero as the clearance to any agent vanishes."""
        robot = env.robot.pos
        scale = 1.0
        for agent in env.scene.agents:
            clearance = float(np.linalg.norm(agent.pos - robot)) - agent.D_S
            band = self.guard_factor * max(agent.D_C - agent.D_S, 1e-6)
            if band > 0.0 and clearance < band:
                scale = min(scale, max(0.0, clearance / band))
        if scale < 1.0:
            v *= scale
        return v, omega

    # -- planning ----------------------------------------------------------

    def __call__(self, env: ConstructionEnv) -> tuple[float, float]:
        if env._robot_reached_goal():
            return 0.0, 0.0

        samples, weights = self._agent_modes(env)
        candidates = self._manoeuvres(env)
        scored = [(self._score(env, c, samples, weights), c) for c in candidates]

        feasible = [(cost, c) for (cost, hard), c in scored if hard <= 1e-9]
        if feasible:
            cost, chosen = min(feasible, key=lambda t: t[0])
            self.last_infeasible = False
        else:
            # No manoeuvre is safe under every predicted mode: maximise clearance
            # (equivalently, minimise the hard violation) rather than progress.
            (cost, _hard), chosen = min(scored, key=lambda t: t[0][1])
            self.last_infeasible = True

        self.last_cost = float(cost)
        v, omega = chosen.command
        if self.hard_filter:
            v, omega = self._guard(env, v, omega)
        return float(v), float(omega)


def predictor_planner(
    predictor,
    *,
    oracle: bool = False,
    safety_diffusion: bool = False,
    **kwargs,
) -> JointPlanner:
    """Convenience constructor used by the evaluation script."""
    return JointPlanner(
        predictor=predictor,
        oracle=oracle,
        safety_diffusion=safety_diffusion,
        **kwargs,
    )
